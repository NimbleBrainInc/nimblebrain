/**
 * Write `COVERAGE.md`: which parity inventory items this suite covers, which
 * only existing tests cover, and which nothing covers yet.
 *
 *   bun --no-env-file test/parity/coverage.ts           write it
 *   bun --no-env-file test/parity/coverage.ts --check   fail when it is out of date
 *
 * Inputs: `inventory.json` (the items), the scenarios' `covers`, and
 * `existing-coverage.json` (item id → the existing test files that exercise it).
 */

import { join } from "node:path";
import { SCENARIOS } from "./scenarios/index.ts";
import { type InventoryItem, loadBaseline, loadInventory } from "./suite.ts";

const DIR = import.meta.dir;
const OUT = join(DIR, "COVERAGE.md");

const HARNESS_ORDER = ["parity", "contract", "browser", "pressure", "eval"];
const USE_ORDER = ["H", "M", "L", "—"];

/** A markdown table; `numeric` right-aligns every column after the first. */
function table(header: string[], rows: string[][], numeric = true): string {
  return [
    `| ${header.join(" | ")} |`,
    `|${header.map((_, i) => (i === 0 || !numeric ? "---" : "---:")).join("|")}|`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");
}

export async function renderCoverage(): Promise<string> {
  const inventory = await loadInventory();
  const baseline = await loadBaseline();
  const existing = (await Bun.file(join(DIR, "existing-coverage.json")).json()) as Record<
    string,
    string[]
  >;

  const byItem = new Map<string, string[]>();
  for (const s of SCENARIOS) {
    for (const id of s.covers) byItem.set(id, [...(byItem.get(id) ?? []), s.id]);
  }
  const items = [...inventory.values()];
  const suite = (i: InventoryItem) => byItem.has(i.id);
  const onlyExisting = (i: InventoryItem) => !suite(i) && (existing[i.id]?.length ?? 0) > 0;
  const none = (i: InventoryItem) => !suite(i) && !onlyExisting(i);
  const count = (list: InventoryItem[], f: (i: InventoryItem) => boolean) => list.filter(f).length;

  const areas = [...new Set(items.map((i) => i.area))];
  const areaRows = areas.map((area) => {
    const list = items.filter((i) => i.area === area);
    return [
      area,
      `${list.length}`,
      `${count(list, suite)}`,
      `${count(list, onlyExisting)}`,
      `${count(list, none)}`,
    ];
  });
  areaRows.push([
    "**Total**",
    `**${items.length}**`,
    `**${count(items, suite)}**`,
    `**${count(items, onlyExisting)}**`,
    `**${count(items, none)}**`,
  ]);

  const parityRows = USE_ORDER.filter((u) =>
    items.some((i) => i.use === u && i.harness === "parity"),
  ).map((u) => {
    const list = items.filter((i) => i.use === u && i.harness === "parity");
    return [
      u,
      `${list.length}`,
      `${count(list, suite)}`,
      `${count(list, onlyExisting)}`,
      `${count(list, none)}`,
    ];
  });

  const harnessRows = HARNESS_ORDER.map((h) => {
    const list = items.filter((i) => i.harness === h);
    return [
      h,
      `${list.length}`,
      `${count(list, suite)}`,
      `${count(list, onlyExisting)}`,
      `${count(list, none)}`,
    ];
  });

  const statusRows = ["same", "moved", "changed-by-decision", "unknown", "missing"].map((st) => {
    const list = items.filter((i) => i.status === st);
    return [
      st,
      `${list.length}`,
      `${count(list, suite)}`,
      `${count(list, onlyExisting)}`,
      `${count(list, none)}`,
    ];
  });

  const scenarioRows = SCENARIOS.map((s) => [
    `\`${s.id}\``,
    s.title,
    (s.requires ?? []).join(", ") || "—",
    s.covers.join(", "),
  ]);

  const beyond = [...byItem.keys()].filter((id) => !inventory.has(id)).sort();

  const nextParity = items
    .filter((i) => i.harness === "parity" && !suite(i))
    .sort(
      (a, b) =>
        USE_ORDER.indexOf(a.use) - USE_ORDER.indexOf(b.use) ||
        a.id.localeCompare(b.id, "en", { numeric: true }),
    );
  const nextRows = nextParity
    .filter((i) => i.use === "H")
    .map((i) => [
      i.id,
      i.item.replace(/\|/g, "\\|"),
      i.status,
      existing[i.id]?.join("<br>") ?? "—",
    ]);

  const uncovered = items
    .filter(none)
    .sort((a, b) => a.id.localeCompare(b.id, "en", { numeric: true }))
    .map((i) => `${i.id} (${i.use}, ${i.harness})`);

  const baselineRows = Object.entries(baseline).map(([id, finding]) => [
    id,
    finding.replace(/\|/g, "\\|"),
  ]);

  return `# Parity coverage

Generated by \`bun --no-env-file test/parity/coverage.ts\` from \`inventory.json\`, the
scenarios' \`covers\` and \`existing-coverage.json\`; \`bun run check:parity-coverage\` fails
when it is out of date. Edit those inputs, never this file.

- **Parity suite**: a scenario in \`scenarios/\` declares the item. It runs against this tree
  and against any other (\`PARITY_TREE\`, \`PARITY_BASE_URL\`), so it says whether the two agree.
- **Existing tests only**: no scenario declares the item, and a test in \`test/\` (an
  integration test, a contract runner through its conformance test, a unit or web test)
  exercises it (\`existing-coverage.json\`, by file). Those run against this tree only: they
  hold the behaviour in place, but do not compare it with \`main\`.
- **Not covered**: neither.

Items whose inventory status is \`changed-by-decision\` are checked for next/engine's decided
behaviour, so \`main\` fails them by design. An \`unknown\` item a scenario covers is checked for
the behaviour this tree has, with the inventory id in a comment beside the check, until it is
settled as decided or fixed.

## By area

${table(["Area", "Items", "Parity suite", "Existing tests only", "Not covered"], areaRows)}

## By the harness the inventory names

${table(["Harness", "Items", "Parity suite", "Existing tests only", "Not covered"], harnessRows)}

Items the inventory assigns to the parity harness, by use rank:

${table(["Use", "Items", "Parity suite", "Existing tests only", "Not covered"], parityRows)}

## By inventory status

${table(["Status", "Items", "Parity suite", "Existing tests only", "Not covered"], statusRows)}

## Scenarios

${table(["Scenario", "What it does", "Needs", "Items"], scenarioRows, false)}

Ids outside the inventory (behaviour it does not list): ${beyond.join(", ") || "none"}.

- NEW-CAT-1: Browse builds its rows from the listing and opens no artifact.
- NEW-CAT-2: install by \`name@catalog\` fetches the artifact once.
- NEW-CAT-3: a plugin's managed skill refuses edits and offers \`skills__copy\`.
- NEW-FI-1: a file an agent writes in chat carries a \`files://\` link that the download door serves.
- NEW-MCP-1: a host context a caller forges at \`/mcp/<wsId>\` is ignored.

## Known findings (the baseline)

\`expected-failures.json\` lists the items this tree fails, each with its repro. A graded run
fails on a failure outside it and on an entry that passes; the change that fixes a finding
removes its entry.

${baselineRows.length > 0 ? table(["Item", "Finding and repro"], baselineRows, false) : "None."}

## Next: high-use parity items no scenario covers

${table(["Item", "What", "Inventory status", "Existing tests"], nextRows, false)}

${nextParity.length - nextRows.length} medium- and low-use parity items are also uncovered by the suite.

## Not covered by any test

${uncovered.length} items: ${uncovered.join(", ")}.
`;
}

if (import.meta.main) {
  const text = await renderCoverage();
  if (process.argv.includes("--check")) {
    const current = await Bun.file(OUT)
      .text()
      .catch(() => "");
    if (current !== text) {
      console.error(
        "test/parity/COVERAGE.md is out of date: run `bun --no-env-file test/parity/coverage.ts`",
      );
      process.exit(1);
    }
  } else {
    await Bun.write(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
