"""The SQL this library emits, pinned byte for byte.

Migrations call the policy renderers inside alembic versions, so a change to
what they render is a schema change: a replayed migration would build different policies than
the ones running in a database today. The sessions bind the GUCs those policies read, so their
statements are part of the same contract.

The golden files under ``golden/`` are frozen output, not generated by the test. A test that
fails here means the emitted SQL changed. If that change is intended it needs its own
migration, and only then a deliberate edit to the golden file.

The table names are fictional. They keep the shapes a real schema has: one-word and
multi-word names, and names that are a prefix of another (``beacon``, ``beacon_ridge``).
"""

